package uz.mukhammad.projectplanner.export.service;

import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import uz.mukhammad.projectplanner.config.AppProperties;
import uz.mukhammad.projectplanner.export.ExcelWriter;
import uz.mukhammad.projectplanner.export.records.ExportFile;
import uz.mukhammad.projectplanner.milestone.entity.Milestone;
import uz.mukhammad.projectplanner.milestone.records.MilestoneList;
import uz.mukhammad.projectplanner.milestone.service.MilestoneService;
import uz.mukhammad.projectplanner.project.entity.Project;
import uz.mukhammad.projectplanner.project.service.ProjectService;
import uz.mukhammad.projectplanner.report.PortfolioService.PortfolioService;
import uz.mukhammad.projectplanner.report.records.PmCompliance;
import uz.mukhammad.projectplanner.report.records.PortfolioReport;
import uz.mukhammad.projectplanner.report.records.ProjectSummary;
import uz.mukhammad.projectplanner.report.records.Workload;
import uz.mukhammad.projectplanner.risk.entity.Risk;
import uz.mukhammad.projectplanner.risk.records.ProjectHealth;
import uz.mukhammad.projectplanner.risk.repository.RiskRepository;
import uz.mukhammad.projectplanner.risk.service.ProjectHealthService;
import uz.mukhammad.projectplanner.task.entity.Task;
import uz.mukhammad.projectplanner.task.entity.TaskHistory;
import uz.mukhammad.projectplanner.task.enums.TaskStatus;
import uz.mukhammad.projectplanner.task.repository.TaskHistoryRepository;
import uz.mukhammad.projectplanner.task.repository.TaskRepository;
import uz.mukhammad.projectplanner.task.service.ProgressService;
import uz.mukhammad.projectplanner.user.User;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.time.Instant;
import java.time.LocalDate;
import java.time.ZoneId;
import java.time.temporal.ChronoUnit;
import java.util.List;

@Service
@RequiredArgsConstructor
public class ExportService {

    private final ProjectService projectService;
    private final PortfolioService portfolioService;
    private final TaskRepository taskRepository;
    private final TaskHistoryRepository historyRepository;
    private final RiskRepository riskRepository;
    private final MilestoneService milestoneService;
    private final ProgressService progressService;
    private final ProjectHealthService healthService;
    private final AppProperties appProperties;


    @Transactional(readOnly = true)
    public ExportFile projectWorkbook(User actor, String projectCode) {
        Project p = projectService.getByCode(projectCode);
        projectService.requireCanManage(actor, p);

        ZoneId zone = appProperties.timezone();
        LocalDate today = LocalDate.now(zone);
        List<Task> tasks = taskRepository.findByProjectOrderByNumberAsc(p);
        MilestoneList ml = milestoneService.list(p);

        try (ExcelWriter x = new ExcelWriter(zone)) {
            // --- Summary ---
            ProjectHealth health = healthService.assess(p);
            ExcelWriter.SheetWriter summary = x.sheet("Summary", 24, 50);
            summary.header("Field", "Value")
                    .row("Project", p.getCode() + " · " + p.getName())
                    .row("Client", p.getClient())
                    .row("Project Manager", p.getProjectManager().getShortName())
                    .row("Status", p.getStatus().name())
                    .row("Health", health.atRisk() ? "At risk (" + health.reason() + ")" : "On track")
                    .row("Start date", p.getStartDate())
                    .row("Planned end date", p.getPlannedEndDate())
                    .row("Progress, %", progressService.progressOf(p))
                    .row("Milestones done", ml.completed() + " / " + ml.milestones().size())
                    .row("Milestones missed", ml.missed())
                    .row("Generated", Instant.now())
                    .row("Generated by", actor.getShortName())
                    .blank()
                    .row("Tasks by status", "");
            for (TaskStatus s : TaskStatus.values()) {
                summary.row("  " + s.name(), tasks.stream().filter(t -> t.getStatus() == s).count());
            }

            // --- Tasks ---
            ExcelWriter.SheetWriter ts = x.sheet("Tasks", 10, 40, 13, 10, 20, 12, 12, 10, 30, 17, 9, 35);
            ts.header("Key", "Title", "Status", "Priority", "Responsible", "Start", "Deadline",
                    "Progress, %", "Deliverable", "Completed at", "Overdue", "Blocked reason");
            for (Task t : tasks) {
                boolean overdue = t.getStatus() != TaskStatus.COMPLETED && t.getDeadline().isBefore(today);
                ts.row(t.getKey(), t.getTitle(), t.getStatus().name(), t.getPriority().getLabel(),
                        t.getAssignee().getShortName(), t.getStartDate(), t.getDeadline(), t.getProgress(),
                        t.getDeliverable(), t.getCompletedAt(), overdue, t.getBlockedReason());
            }

            // --- Milestones ---
            ExcelWriter.SheetWriter ms = x.sheet("Milestones", 40, 12, 12, 9, 17);
            ms.header("Milestone", "Due date", "Status", "Missed", "Completed at");
            for (Milestone m : ml.milestones()) {
                ms.row(m.getName(), m.getDueDate(), m.getStatus().name(), m.isMissed(today), m.getCompletedAt());
            }

            // --- Risks ---
            ExcelWriter.SheetWriter rs = x.sheet("Risks", 10, 50, 20, 9, 17, 17);
            rs.header("Severity", "Description", "Owner", "Status", "Raised", "Closed");
            for (Risk r : riskRepository.findByProjectOrderByCreatedAtAsc(p)) {
                rs.row(r.getSeverity().getLabel(), r.getDescription(), r.getOwner().getShortName(),
                        r.getStatus().name(), r.getCreatedAt(), r.getClosedAt());
            }

            // --- History (полная, без лимита 20) ---
            ExcelWriter.SheetWriter hs = x.sheet("History", 17, 10, 20, 13, 25, 25, 40);
            hs.header("When", "Task", "By", "Change", "Old value", "New value", "Comment");
            for (TaskHistory h : historyRepository.findByTask_ProjectOrderByChangedAtAscIdAsc(p)) {
                hs.row(h.getChangedAt(), h.getTask().getKey(), h.getChangedBy().getShortName(),
                        h.getChangeType().name(), h.getOldValue(), h.getNewValue(), h.getComment());
            }

            return new ExportFile(p.getCode() + "_report_" + today + ".xlsx", x.toBytes());
        } catch (IOException e) {
            throw new UncheckedIOException("Failed to build Excel for " + p.getCode(), e);
        }
    }

    // ===================== Портфель =====================

    @Transactional(readOnly = true)
    public ExportFile portfolioWorkbook(User actor) {
        PortfolioReport r = portfolioService.build(actor); // проверит роль сам
        ZoneId zone = appProperties.timezone();

        try (ExcelWriter x = new ExcelWriter(zone)) {
            ExcelWriter.SheetWriter ps = x.sheet("Projects", 8, 30, 20, 10, 10, 30, 8, 8, 10, 12);
            ps.header("Code", "Name", "PM", "Progress, %", "Health", "Health reason",
                    "Open", "Overdue", "Missed MS", "Planned end");
            for (ProjectSummary s : r.projects()) {
                ps.row(s.project().getCode(), s.project().getName(), s.project().getProjectManager().getShortName(),
                        s.progress(), s.health().atRisk() ? "At risk" : "On track",
                        s.health().atRisk() ? s.health().reason() : "",
                        s.open(), s.overdue(), s.missedMilestones(), s.project().getPlannedEndDate());
            }

            ExcelWriter.SheetWriter os = x.sheet("Overdue", 8, 10, 40, 20, 12, 10);
            os.header("Project", "Task", "Title", "Responsible", "Deadline", "Days late");
            for (Task t : r.overdue()) {
                os.row(t.getProject().getCode(), t.getKey(), t.getTitle(), t.getAssignee().getShortName(),
                        t.getDeadline(), ChronoUnit.DAYS.between(t.getDeadline(), r.today()));
            }

            ExcelWriter.SheetWriter ws = x.sheet("Workload", 22, 8, 9, 11);
            ws.header("Person", "Open", "Overdue", "Overloaded");
            for (Workload w : r.workload()) {
                ws.row(w.user().getShortName(), w.open(), w.overdue(), w.overloaded());
            }

            ExcelWriter.SheetWriter ks = x.sheet("Key risks", 8, 10, 50, 20);
            ks.header("Project", "Severity", "Description", "Owner");
            for (Risk risk : r.keyRisks()) {
                ks.row(risk.getProject().getCode(), risk.getSeverity().getLabel(),
                        risk.getDescription(), risk.getOwner().getShortName());
            }

            ExcelWriter.SheetWriter cs = x.sheet("PM reporting", 8, 20, 17, 17, 11);
            cs.header("Project", "PM", "Last report", "Last activity", "Compliant");
            for (PmCompliance c : r.pmCompliance()) {
                cs.row(c.project().getCode(), c.pm().getShortName(), c.lastReport(), c.lastActivity(), c.compliant());
            }

            return new ExportFile("portfolio_" + r.today() + ".xlsx", x.toBytes());
        } catch (IOException e) {
            throw new UncheckedIOException("Failed to build portfolio Excel", e);
        }
    }
}